/** 这个识别主模型族认的语言；不是识别主模型的 family 为 null。 */
export function transcribeLanguages(family: ModelFamily): readonly string[] | null {
  switch (family) {
    case 'qwen3-asr':
      return QWEN3_ASR_LANGUAGES;
    case 'whisper-mlx':
    case 'whisper-coreml':
    case 'whisper-ggml':
      return WHISPER_LANGUAGES;
    case 'moss-transcribe-diarize':
      return MOSS_LANGUAGES;
    default:
      return null;
  }
}
