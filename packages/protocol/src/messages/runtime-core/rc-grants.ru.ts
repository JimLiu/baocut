import type { RcGrantsMessages } from './rc-grants.ts';

const ZH_KINDS: Readonly<Record<string, string>> = {
  transcript: 'расшифровки и переводы',
  frames: 'кадры и миниатюры',
  audio: 'аудио',
  video: 'исходное видео',
  document: 'текст и запросы',
  context: 'контекст разговора с агентом',
};

function ruKinds(codes: string): string {
  return codes
    .split(',')
    .filter(Boolean)
    .map((k) => ZH_KINDS[k] ?? k)
    .join(', ');
}

