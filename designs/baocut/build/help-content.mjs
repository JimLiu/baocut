/* 原型帮助正文来自当前共享 UI 的中文消息；不依赖已移除的 apps/shared。 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { transformSync } from 'esbuild';

export function helpGuides(repo) {
  const model = fs.readFileSync(path.join(repo, 'packages/ui/src/model/help-guides.ts'), 'utf8');
  const rows = model.match(/const GUIDES:[\s\S]*?= (\[[\s\S]*?\n\]);/);
  if (!rows) throw new Error('Help guide metadata not found');
  const metadata = vm.runInNewContext(rows[1]);
  const source = fs.readFileSync(path.join(repo, 'packages/ui/src/model/help-guides.zh-Hans.ts'), 'utf8');
  const module = {exports: {}};
  vm.runInNewContext(transformSync(source, {loader: 'ts', format: 'cjs'}).code, {module, exports: module.exports});
  const content = module.exports.zhHans.guides;
  return metadata.map(([id, icon, group, minutes, action]) => ({id, icon, group, minutes, action, ...content[id], cta: content[id].cta ?? '回到视频'}));
}
export function helpModule(repo) {
  return `/* @generated by build/help-content.mjs from packages/ui/src/model/help-guides*.ts. */
(function () {
  const guides = ${JSON.stringify(helpGuides(repo), null, 2)};
  function search(query) {
    const terms = String(query || '').trim().toLowerCase().split(/\\s+/).filter(Boolean);
    return guides.filter(g => {
      const text = [g.title, g.short, g.summary, g.keywords, g.tip, ...g.steps.flat()].filter(part => typeof part === 'string').join(' ').toLowerCase();
      return terms.every(term => text.includes(term));
    });
  }
  window.BC_HELP = {guides, search};
})();
`;
}
