/* Home 模板库的数据：从仓库顶层 templates/<id>/（template.json + prompt.md，见 docs/spec/template-spec.md）
   读出内置模板，生成浏览器与 node --test 都能直接加载的 app/model-home-templates-data.js。
   原型是纯浏览器 IIFE，运行时读不到仓库文件，所以由 build.mjs 在构建时重建这份入库的生成物；
   build --check（build.test.cjs）会抓 templates/ 与生成物不一致。 */
import fs from 'node:fs';
import path from 'node:path';

export const HOME_TEMPLATES_DATA = 'app/model-home-templates-data.js';

/** 一个模板目录 → 原型用到的字段。清单里没写的 ratio / durationSeconds / brief 写成 null（= 自动 / 没有），
    fields / skills 没写时是空数组（template-spec §3.1、§5.5）。
    封面图与预览视频只带成「有没有」（原型不读文件，仍画占位封面）；验证记录 verification 不进原型。 */
function entry(dir) {
  const m = JSON.parse(fs.readFileSync(path.join(dir, 'template.json'), 'utf8'));
  const prompt = fs.readFileSync(path.join(dir, 'prompt.md'), 'utf8').trim();
  return {
    id: m.id, version: m.version, kind: m.kind, category: m.category,
    title: m.title, summary: m.summary, description: m.description,
    ratio: m.ratio || null, durationSeconds: m.durationSeconds || null,
    brief: m.brief || null, fields: (m.fields || []).map((f) => ({label: f.label, hint: f.hint || null, example: f.example || null})),
    skills: m.skills || [],
    source: m.source, author: m.author, tags: m.tags || [],
    cover: {tone: m.cover.tone || null, figure: m.cover.figure || null, kicker: m.cover.kicker || null},
    beats: (m.preview && m.preview.beats) || [],
    files: {cover: Boolean(m.cover.file), preview: Boolean(m.preview && m.preview.file)},
    assets: (m.assets || []).map((a) => ({path: a.path, type: a.type, note: a.note})),
    prompt,
  };
}

/** templatesDir 下全部模板（按 id 排序，输出确定）生成的模块文本。 */
export function homeTemplatesModule(templatesDir) {
  const list = fs.readdirSync(templatesDir, {withFileTypes: true})
    .filter((d) => d.isDirectory() && !d.name.startsWith('.') && fs.existsSync(path.join(templatesDir, d.name, 'template.json')))
    .map((d) => d.name).sort()
    .map((name) => entry(path.join(templatesDir, name)));
  return `/* @generated by build/home-templates.mjs from templates/<id>/template.json + prompt.md. 不要手改：npm run build 重建。 */
(function () {
  const DATA = ${JSON.stringify(list, null, 2).replace(/\n/g, '\n  ')};
  if (typeof window !== 'undefined') window.BC_HOME_TEMPLATE_DATA = DATA;
  if (typeof module !== 'undefined') module.exports = DATA;
})();
`;
}
