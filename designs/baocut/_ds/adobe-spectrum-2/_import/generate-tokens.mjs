#!/usr/bin/env node
/*
 * Regenerates tokens/*.css + tokens/tokens.json from the authoritative Adobe
 * token data. Nothing here is hand-written: every value traces to
 * @adobe/spectrum-tokens, the exact version @react-spectrum/s2 depends on.
 *
 *   npm pack @adobe/spectrum-tokens@<version> && tar xzf *.tgz
 *   node generate-tokens.mjs <path-to-package/dist/json/variables.json>
 *
 * See ../readme.md "Sources" for provenance and how to bump the version.
 */
import fs from 'fs';
import path from 'path';
import {fileURLToPath} from 'url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'tokens');
const src = process.argv[2];
if (!src) {
  console.error('usage: generate-tokens.mjs <variables.json>');
  process.exit(1);
}
const V = JSON.parse(fs.readFileSync(src, 'utf8'));

/* ---------- resolution ---------- */
// Tokens nest two independent axes: a theme axis (light/dark/wireframe) and a
// scale axis (desktop/mobile). An alias carries both — outer set picks the
// theme context, the inner set picks the value within it — so resolve walks
// down the same axis it entered on.
function resolve(node, axis, depth = 0) {
  if (node == null || depth > 12) return null;
  if (node.sets) {
    const next = node.sets[axis] ?? node.sets.light ?? node.sets.desktop;
    if (next) return resolve(next, axis, depth + 1);
    return null;
  }
  if (typeof node.value === 'string' || typeof node.value === 'number') {
    const val = node.value;
    if (typeof val === 'string' && /^\{.+\}$/.test(val)) {
      return resolve(V[val.slice(1, -1)], axis, depth + 1);
    }
    return val;
  }
  if (node.ref) return resolve(V[node.ref.replace(/[{}]/g, '')], axis, depth + 1);
  return null;
}
const get = (name, axis) => (V[name] ? resolve(V[name], axis) : null);

function hex(val) {
  if (typeof val !== 'string') return null;
  const m = val.match(/^rgb\((\d+),\s*(\d+),\s*(\d+)\)$/);
  if (m) return '#' + [1, 2, 3].map((i) => (+m[i]).toString(16).padStart(2, '0')).join('').toUpperCase();
  if (/^#[0-9a-f]{6}$/i.test(val)) return val.toUpperCase();
  if (/^rgba?\(/.test(val)) return val;
  return null;
}
// Every color ships as light-dark() so one stylesheet themes both ways.
function pair(name) {
  const l = hex(get(name, 'light'));
  const d = hex(get(name, 'dark'));
  if (!l) return null;
  return !d || d === l ? l : `light-dark(${l}, ${d})`;
}

/* ---------- selection ---------- */
const HUES = ['gray', 'blue', 'red', 'orange', 'yellow', 'green', 'celery', 'chartreuse', 'cyan',
  'indigo', 'magenta', 'fuchsia', 'purple', 'seafoam', 'pink', 'turquoise', 'brown', 'silver', 'cinnamon'];
const isPaletteStop = (k) => HUES.some((h) => new RegExp(`^${h}-\\d+$`).test(k));
const isAlias = (k) => /-color(-\d+)?$/.test(k) || /-color-(default|hover|down|key-focus|selected|disabled)$/.test(k) ||
  /^(accent|negative|positive|notice|informative)-/.test(k) || /background-color|-text-color|border-color/.test(k);

const banner = (what) =>
  `/* Spectrum 2 — ${what}\n   Generated by _import/generate-tokens.mjs from @adobe/spectrum-tokens.\n   Do not hand-edit; regenerate instead. */\n`;

const flat = {colors: {}, layout: {}, typography: {}};

/* ---------- colors.css: the raw palette ---------- */
{
  const lines = [banner('color palette (19 hues x 13-16 stops)'), ':root {'];
  for (const hue of HUES) {
    const stops = Object.keys(V).filter((k) => new RegExp(`^${hue}-\\d+$`).test(k))
      .sort((a, b) => parseInt(a.split('-').pop()) - parseInt(b.split('-').pop()));
    if (!stops.length) continue;
    lines.push(`\n  /* ${hue} */`);
    for (const k of stops) {
      const p = pair(k);
      if (!p) continue;
      lines.push(`  --${k}: ${p};`);
      flat.colors[k] = {light: hex(get(k, 'light')), dark: hex(get(k, 'dark'))};
    }
  }
  lines.push('}\n');
  fs.writeFileSync(path.join(OUT, 'colors.css'), lines.join('\n'));
}

/* ---------- semantic-colors.css: the aliases products actually reach for ---------- */
{
  const keys = Object.keys(V).filter((k) => !isPaletteStop(k) && isAlias(k))
    .filter((k) => pair(k)).sort();
  const lines = [banner('semantic color aliases'), ':root {'];
  for (const k of keys) {
    lines.push(`  --${k}: ${pair(k)};`);
    flat.colors[k] = {light: hex(get(k, 'light')), dark: hex(get(k, 'dark'))};
  }
  lines.push('}\n');
  fs.writeFileSync(path.join(OUT, 'semantic-colors.css'), lines.join('\n'));
}

/* ---------- layout.css ---------- */
{
  const groups = [
    ['spacing', /^spacing-\d+$/],
    ['corner radius', /^corner-radius-/],
    ['border width', /^border-width-\d+$/],
    ['component height (desktop)', /^component-height-\d+$/],
    ['workflow icon size (desktop)', /^workflow-icon-size-\d+$/],
    ['text to visual / text to control', /^text-to-(visual|control)-\d+$/],
    ['edge to text / edge to visual', /^(edge-to-text|edge-to-visual)/],
    ['focus indicator', /^focus-indicator-/],
    ['field / control internals', /^(field-label|field-edge)/],
  ];
  const lines = [banner('layout tokens (desktop scale)'), ':root {'];
  for (const [label, re] of groups) {
    const keys = Object.keys(V).filter((k) => re.test(k)).sort((a, b) => {
      const na = parseInt(a.split('-').pop()), nb = parseInt(b.split('-').pop());
      return Number.isNaN(na) || Number.isNaN(nb) ? a.localeCompare(b) : na - nb;
    });
    const rows = [];
    for (const k of keys) {
      const val = get(k, 'desktop');
      if (val == null || typeof val === 'object') continue;
      const out = typeof val === 'number' ? (k.includes('corner-radius') ? '9999px' : String(val)) : val;
      rows.push(`  --${k}: ${out};`);
      flat.layout[k] = out;
    }
    if (rows.length) lines.push(`\n  /* ${label} */`, ...rows);
  }
  lines.push('}\n');
  fs.writeFileSync(path.join(OUT, 'layout.css'), lines.join('\n'));
}

/* ---------- typography.css ---------- */
{
  const lines = [banner('typography tokens (desktop scale)'), ':root {',
    "  /* families — Adobe Clean is proprietary; Adobe's own open-source",
    '     Source faces stand in and Clean is listed first for licensed hosts. */',
    "  --font-family-sans: 'Adobe Clean', 'Source Sans 3', ui-sans-serif, system-ui, -apple-system, 'Helvetica Neue', sans-serif;",
    "  --font-family-serif: 'Adobe Clean Serif', 'Source Serif 4', Georgia, serif;",
    "  --font-family-code: 'Adobe Clean Mono', 'Source Code Pro', ui-monospace, 'SF Mono', Menlo, monospace;"];
  const groups = [
    ['weights', /-font-weight$/],
    ['line heights', /^(line-height-|body-line-height|heading-line-height|detail-line-height|code-line-height)/],
    ['font size scale', /^font-size-\d+$/],
    ['role sizes', /^(heading|body|detail|code|title)-size-/],
  ];
  for (const [label, re] of groups) {
    const keys = Object.keys(V).filter((k) => re.test(k)).sort((a, b) => {
      const na = parseInt(a.split('-').pop()), nb = parseInt(b.split('-').pop());
      return Number.isNaN(na) || Number.isNaN(nb) ? a.localeCompare(b) : na - nb;
    });
    const rows = [];
    for (const k of keys) {
      const val = get(k, 'desktop');
      if (val == null || typeof val === 'object') continue;
      rows.push(`  --${k}: ${val};`);
      flat.typography[k] = val;
    }
    if (rows.length) lines.push(`\n  /* ${label} */`, ...rows);
  }
  lines.push('}\n');
  fs.writeFileSync(path.join(OUT, 'typography.css'), lines.join('\n'));
}

fs.writeFileSync(path.join(OUT, 'tokens.json'), JSON.stringify(flat, null, 1));
console.log('colors', Object.keys(flat.colors).length, '· layout', Object.keys(flat.layout).length, '· typography', Object.keys(flat.typography).length);

/* ---------- artboard-tokens.css ----------
 * The block every .dc.html artboard embeds verbatim. A published artboard has
 * no network egress and cannot link a stylesheet, so the system travels inside
 * the file and check-conformance.mjs diffs it back against this generator.
 * Short aliases (--g25, --b900 …) are kept so existing rules keep resolving;
 * anything new should reach for the full Spectrum name.
 */
{
  // Only the stops the artboards actually paint with. Grays and blue carry the
  // chrome; the rest are the categorical hues the timeline rows, status
  // surfaces and speaker attribution draw from.
  // The 700 stop on the categorical hues is the timeline row's hover/selected
  // border (§12.7): each category's palette carries four roles — background,
  // border, hover-border, text — and 200/300/400/1000 only covered three, so the
  // hover border had nothing to point at.
  const stops = {
    gray: [25, 50, 75, 100, 200, 300, 400, 500, 600, 700, 800, 900, 1000],
    blue: [100, 200, 300, 400, 500, 600, 800, 900, 1000, 1100],
    red: [100, 200, 300, 400, 700, 900, 1000, 1100],
    orange: [100, 200, 300, 400, 600, 700, 900, 1000, 1100],
    green: [100, 200, 300, 400, 700, 900, 1000, 1100],
    yellow: [100, 200, 300, 400, 700, 1000, 1100],
    purple: [200, 300, 400, 700, 1000],
    cyan: [200, 300, 400, 700, 1000],
    magenta: [200, 300, 400, 700, 1000],
    seafoam: [200, 300, 400, 700, 1000],
    indigo: [200, 300, 400, 700, 1000],
    brown: [200, 300, 400, 700, 1000],
    cinnamon: [1000]
  };
  const L = [];
  L.push('/* @ds tokens: adobe-spectrum-2 */');
  L.push('/* Generated — do not hand-edit. Regenerate with _ds/adobe-spectrum-2/_import/generate-tokens.mjs');
  L.push('   and paste between the @ds markers; check-conformance.mjs enforces the match.');
  L.push("   Deviation on purpose: Source Sans 3 leads the stack instead of Adobe Clean, so the");
  L.push('   artboard measures the same on every machine whether or not Clean is licensed. */');
  L.push("--sans: 'Source Sans 3', 'Adobe Clean', ui-sans-serif, system-ui, -apple-system, 'Helvetica Neue', sans-serif;");
  L.push("--mono: 'Source Code Pro', 'Adobe Clean Mono', ui-monospace, 'SF Mono', Menlo, monospace;");
  for (const [hue, list] of Object.entries(stops)) {
    L.push(list.map((n) => `--${hue}-${n}:${pair(`${hue}-${n}`)};`).join(' '));
  }
  L.push(`--focus-ring:${pair('focus-indicator-color')};`);
  // Motion is code, not token data: spectrum-theme.ts `transition()` sets 150ms
  // and `timingFunction.default` the curve below. Kept in sync by hand with
  // components/control-geometry.json "motion".
  L.push('--ease: 150ms cubic-bezier(0.45,0,0.4,1);');
  L.push('--sh-pop: 0px 2px 8px 0px rgba(0,0,0,0.08), 0px 1px 4px 0px rgba(0,0,0,0.04), 0px 0px 1px 0px rgba(0,0,0,0.08);');
  L.push('--sh-elev: 0px 4px 12px 0px rgba(0,0,0,0.08), 0px 2px 6px 0px rgba(0,0,0,0.04), 0px 0px 2px 0px rgba(0,0,0,0.12);');
  L.push('/* legacy short aliases */');
  L.push(stops.gray.map((n) => `--g${n}:var(--gray-${n});`).join(' '));
  L.push([100, 200, 300, 400, 800, 900, 1000, 1100].map((n) => `--b${n}:var(--blue-${n});`).join(' '));
  L.push('--red:var(--red-900); --orange:var(--orange-600); --green:var(--green-900);');
  L.push('/* @ds end */');
  fs.writeFileSync(path.join(OUT, 'artboard-tokens.css'), L.join('\n') + '\n');
  console.log('artboard-tokens.css written');
}
