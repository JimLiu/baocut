// Generates the per-character Mandarin reading table used by the virtual-host skill's lip sync
// (skills/baocut/built-in-skills/virtual-host/scripts/pinyin-table.mjs). Readings come from the ICU Han-Latin
// transliterator that ships with macOS Foundation (NSStringTransformMandarinToLatin); tones are dropped because a
// mouth shape does not depend on them. Run on macOS:
//
//   node scripts/pinyin-table/generate.ts [--out <file>]
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const args = process.argv.slice(2);
const outAt = args.indexOf('--out');
const out = outAt >= 0 ? path.resolve(args[outAt + 1]!) : path.join(root, 'skills/baocut/built-in-skills/virtual-host/scripts/pinyin-table.mjs');

if (process.platform !== 'darwin') throw new Error('This generator uses the macOS Foundation transliterator; run it on macOS.');

// CJK Unified Ideographs and Extension A cover everything in GB 18030's two-byte range and common text.
const RANGES: Array<[number, number]> = [
  [0x4e00, 0x9fff],
  [0x3400, 0x4dbf],
];
const chars: string[] = [];
for (const [a, b] of RANGES) for (let c = a; c <= b; c++) chars.push(String.fromCodePoint(c));

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'pinyin-table-'));
try {
  const input = path.join(tmp, 'in.txt');
  const jxa = path.join(tmp, 'transform.js');
  fs.writeFileSync(input, chars.join('\n'));
  fs.writeFileSync(
    jxa,
    `ObjC.import('Foundation');
function run(argv) {
  const s = $.NSString.stringWithContentsOfFileEncodingError(argv[0], $.NSUTF8StringEncoding, null);
  const m = s.mutableCopy;
  m.applyTransformReverseRangeUpdatedRange($.NSStringTransformMandarinToLatin, false, $.NSMakeRange(0, m.length), null);
  m.writeToFileAtomicallyEncodingError(argv[1], true, $.NSUTF8StringEncoding, null);
  return 'ok';
}
`,
  );
  const result = path.join(tmp, 'out.txt');
  execFileSync('osascript', ['-l', 'JavaScript', jxa, input, result], { stdio: ['ignore', 'pipe', 'inherit'] });
  const lines = fs.readFileSync(result, 'utf8').split('\n');
  if (lines.length !== chars.length) throw new Error(`expected ${chars.length} lines, got ${lines.length}`);

  const bySyllable = new Map<string, string[]>();
  let skipped = 0;
  lines.forEach((line, i) => {
    // Tone marks off, ü kept as v (lü and lu are different mouths at the start).
    const plain = line
      .trim()
      .toLowerCase()
      .normalize('NFD')
      .replace(/u\u0308/g, 'v')
      .replace(/\p{M}/gu, '');
    if (!/^[a-z]{1,6}$/.test(plain)) {
      skipped++;
      return;
    }
    const list = bySyllable.get(plain) ?? [];
    list.push(chars[i]!);
    bySyllable.set(plain, list);
  });

  const syllables = [...bySyllable.keys()].sort();
  const body = syllables.map((s) => `  ${s}: '${bySyllable.get(s)!.join('')}',`).join('\n');
  const text = `// i18n-ignore-file: data table, not user-facing text
// Mandarin reading of each Han character, without tones (ü written v), grouped by syllable. Generated by
// scripts/pinyin-table/generate.ts from the ICU Han-Latin transliterator (Unicode License V3) as shipped in macOS
// Foundation. One reading per character, the most common one; phrase-level readings are in visemes.mjs. Do not edit
// by hand.
export const PINYIN = {
${body}
};
`;
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, text);
  const count = [...bySyllable.values()].reduce((n, l) => n + l.length, 0);
  console.log(`${path.relative(root, out)}: ${count} characters in ${syllables.length} syllables, ${skipped} without a reading, ${Buffer.byteLength(text)} bytes`);
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}
